/** Shared color source for first paint, CSS tokens, previews and Vuetify. */
export const alphaPaletteIds = ['blue', 'forest', 'teal', 'violet', 'rose', 'amber'] as const
export type AlphaPalette = typeof alphaPaletteIds[number]
export type AlphaTheme = 'light' | 'dark'
type ColorTokens = Record<string, string>
type Palette = Record<AlphaTheme, ColorTokens>

export function isAlphaPalette(value: unknown): value is AlphaPalette {
  return typeof value === 'string' && (alphaPaletteIds as readonly string[]).includes(value)
}

