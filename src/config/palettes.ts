type VariantColors = Record<'bg' | 'bg-subtle' | 'surface' | 'surface-2' | 'surface-inset' | 'border' | 'border-strong' | 'text' | 'text-secondary' | 'text-tertiary' | 'text-disabled' | 'primary' | 'primary-hover' | 'primary-active' | 'primary-weak' | 'primary-weak-2' | 'primary-border' | 'on-primary', string>

function variant(colors: VariantColors, series: readonly [string, string, string, string, string]): ColorTokens {
  return {
    ...colors,
    'neutral-weak': colors['bg-subtle'],
    'neutral-border': colors.border,
    'chart-revenue': series[0],
    'chart-cash': series[1],
    'chart-expense': series[2],
    'chart-card': series[3],
    'chart-grid': colors.border,
    'chart-axis': colors['text-tertiary'],
    'chart-track': colors['bg-subtle'],
    'chart-target': colors['text-tertiary'],
    'chart-label-on-fill': colors['on-primary'],
    'chord-ribbon': colors['primary-border'],
    'primary-ring': `color-mix(in srgb, ${colors.primary} 28%, transparent)`,
    'color-period-a': series[0],
    'color-period-b': colors['text-tertiary'],
    'c1': series[0],
    'c2': series[1],
    'c3': series[2],
    'c4': series[3],
    'c5': series[4],
  }
}

