export function alphaPaletteTokens(palette: AlphaPalette, mode: AlphaTheme): ColorTokens {
  return { ...forest[mode], ...palettes[palette][mode] }
}

/** First-paint CSS and runtime theme switching use the same registry. */
export function alphaPaletteStyles(): string {
  return alphaPaletteIds.flatMap(palette => (['light', 'dark'] as const).map(mode => {
    const story = alphaPaletteTokens(palette, 'dark')

    const tokens = {
      ...alphaPaletteTokens(palette, mode),
      'login-story-bg': story.bg,
      'login-story-raised': story['primary-weak-2'],
      'login-story-text': story.text,
      'login-story-muted': story['text-secondary'],
      'login-story-accent': story.primary,
      'login-story-on-accent': story['on-primary'],
    }

    const declarations = Object.entries(tokens).map(([key, value]) => `--${key}:${value}`).join(';')
    return `:root[data-palette="${palette}"][data-theme="${mode}"]{${declarations}}`
  })).join('\n')
}

export function alphaPaletteBackgrounds() {
  return Object.fromEntries(alphaPaletteIds.map(palette => [palette, {
    light: alphaPaletteTokens(palette, 'light').bg,
    dark: alphaPaletteTokens(palette, 'dark').bg,
  }]))
}
